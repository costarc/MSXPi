#!/usr/bin/env python3
"""Build PLAYNET.COM (MSXPi path) and its relocatable MSXPi transport.

    python build.py [--assembler sjasmplus] [--sdcc sdcc]   -> build/PLAYNET.COM, build/PLAYNET.OVL, build/transport_*.inc

The transport is assembled at two origins (0 and 100h); every byte that differs is the high byte of an
address inside it, so the word before it is relocated by the loader when it copies the transport to a
game's netplay.transport_area. The game stubs themselves are built by their ROM-Patcher packages
(software/ROM-Patcher/profiles/<game>/rebuild.py), from engine/playnet_engine.asm.
"""
import argparse
from pathlib import Path
import re
import shutil
import subprocess

HERE = Path(__file__).resolve().parent
BUILD = HERE / 'build'
INCLUDE = HERE.parents[2] / 'asm-common/include'


def assemble(assembler, *args):
    done = subprocess.run([assembler, *args], cwd=HERE, capture_output=True, text=True)
    if done.returncode:
        raise SystemExit(done.stdout + done.stderr)


def symbols(path):
    found = {}
    for line in Path(path).read_text().splitlines():
        match = re.match(r'([\w.]+):\s*EQU\s*0x([0-9A-Fa-f]+)', line)
        if match:
            found[match[1]] = int(match[2], 16)
    return found


SHARED = ('tLen', 'tImage', 'tRet', 'tDosA8', 'tDosSub')      # the same offset in both transports


def relocatable(assembler, name):
    """Assemble transport_<name>.asm at 0 and 100h: (image, relocation offsets, symbols)."""
    images = []
    for origin in (0, 0x100):
        raw = BUILD / f'transport_{name}_{origin:x}.bin'
        sym = BUILD / f'transport_{name}_{origin:x}.sym'
        assemble(assembler, f'-DTORG={origin}', f'--raw={raw}', f'--sym={sym}', f'transport_{name}.asm')
        images.append(raw.read_bytes())
    low, high = images
    assert len(low) == len(high)
    relocs = []
    for i, (a, b) in enumerate(zip(low, high)):
        if a != b:
            assert b - a == 1 and i > 0, 'unexpected difference at %d' % i
            relocs.append(i - 1)
    (BUILD / f'transport_{name}.bin').write_bytes(low)
    return low, relocs, symbols(BUILD / f'transport_{name}_0.sym')


def transport(assembler):
    low, relocs, names = relocatable(assembler, 'msxpi')
    lines = ['; generated by build.py from transport_msxpi.asm - do not edit',
             f'TR_SIZE:        EQU     {len(low)}',
             f'TR_IRQ:         EQU     {names["tIrq"] + 1}      ; XIRQ jump target (the game\'s interrupt handler)',
             f'TR_LEN:         EQU     {names["tLen"]}     ; game packet length L',
             f'TR_IMAGE:       EQU     {names["tImage"]}     ; the image\'s AB header',
             f'TR_RET:         EQU     {names["tRet"]}     ; PLAYNET.COM\'s return routine, 0 = reset',
             f'TR_DOSA8:       EQU     {names["tDosA8"]}     ; MSX-DOS\'s slot registers',
             f'TR_DOSSUB:      EQU     {names["tDosSub"]}',
             f'TR_BOOT:        EQU     {names["xBoot"]}    ; the fallback reset, from the return routine',
             'trImage:        INCBIN  "transport_msxpi.bin"',
             'trRelocs:       defw    ' + ', '.join(str(r) for r in relocs) + ', $FFFF']
    (BUILD / 'transport_msxpi.inc').write_text('\n'.join(lines) + '\n')

    ulow, urelocs, unames = relocatable(assembler, 'unapi')
    for field in SHARED:
        assert unames[field] == names[field], field + ' differs between the transports'
    lines = ['; generated by build.py from transport_unapi.asm - do not edit',
             f'TU_SIZE:        EQU     {len(ulow)}',
             f'TU_AREA:        EQU     {unames["TU_AREA"]}    ; transport_area.size it needs',
             f'TU_BOOT:        EQU     {unames["xBoot"]}    ; the fallback reset',
             f'TU_HANDLER:     EQU     {unames["tHandler"]}     ; the game\'s interrupt handler',
             f'TU_OVLSEG:      EQU     {unames["tOvlSeg"]}',
             f'TU_GAMESEG2:    EQU     {unames["tGameSeg2"]}',
             f'TU_IO:          EQU     {unames["tIo"]}     ; the overlay\'s I/O block',
             f'TU_DOSSEG3:     EQU     {unames["tDosSeg3"]}     ; MSX-DOS\'s page-3 segment',
             f'TU_GAMESEG3:    EQU     {unames["tGameSeg3"]}     ; the game\'s',
             f'TU_STACK:       EQU     {unames["tStack"]}     ; the private stack\'s top in MSX-DOS\'s page 3',
             f'TU_PUTP2:       EQU     {unames["tPutP2"] + 1}     ; operand of jp PUT_P2',
             f'TU_TICKS:       EQU     {unames["tTicks"]}     ; the tick counter (netcore\'s clock in the game)',
             'tuImage:        INCBIN  "transport_unapi.bin"',
             'tuRelocs:       defw    ' + ', '.join(str(r) for r in urelocs) + ', $FFFF']
    (BUILD / 'transport_unapi.inc').write_text('\n'.join(lines) + '\n')
    return len(low), len(relocs), len(ulow)


OVL_BASE = 0x8000


def overlay(sdcc):
    """PLAYNET.OVL: netcore + its UNAPI layer (netcore/), linked at 8000h for a mapper segment in page 2.
    The file holds 8000h up to the end of the code; the C data after it is cleared by the INIT entry."""
    out = BUILD / 'ovl'
    out.mkdir(exist_ok=True)
    src = HERE / 'netcore'
    tool = Path(sdcc).parent
    def run(*cmd):
        done = subprocess.run(cmd, cwd=out, capture_output=True, text=True)
        if done.returncode:
            raise SystemExit(done.stdout + done.stderr)
    run(str(tool / 'sdasz80'), '-o', 'ovl_crt0.rel', str(src / 'ovl_crt0.s'))
    for name in ('netcore', 'ovl_main'):
        run(sdcc, '-mz80', '-c', '--opt-code-size', '-I', str(src), str(src / (name + '.c')), '-o', name + '.rel')
    run(sdcc, '-mz80', '--no-std-crt0', '--code-loc', '0x8040', '--data-loc', '0', '-o', 'ovl.ihx',
        'ovl_crt0.rel', 'ovl_main.rel', 'netcore.rel')
    image = bytearray(0x4000)
    top = 0
    for line in (out / 'ovl.ihx').read_text().splitlines():
        n, addr, kind = int(line[1:3], 16), int(line[3:7], 16), int(line[7:9], 16)
        if kind == 0 and n:
            assert OVL_BASE <= addr and addr + n <= OVL_BASE + 0x4000, 'overlay outside 8000h-BFFFh'
            image[addr - OVL_BASE:addr - OVL_BASE + n] = bytes.fromhex(line[9:9 + 2 * n])
            top = max(top, addr + n)
    symbols = {}
    for line in (out / 'ovl.map').read_text().splitlines():
        parts = line.split()
        if len(parts) >= 2 and re.fullmatch(r'[0-9A-F]{8}', parts[0]):
            symbols[parts[1]] = int(parts[0], 16)
    end = symbols['s__DATA'] + symbols['l__DATA']
    assert end <= 0xBF00, 'overlay data reaches %04Xh' % end
    assert top - OVL_BASE <= 0x1800, 'PLAYNET.OVL is above the 6 KB PLAYNET.COM loads it through'
    (BUILD / 'PLAYNET.OVL').write_bytes(bytes(image[:top - OVL_BASE]))
    return top - OVL_BASE, end


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--assembler', default='sjasmplus')
    parser.add_argument('--sdcc', default=shutil.which('sdcc') or 'sdcc')
    args = parser.parse_args()
    BUILD.mkdir(exist_ok=True)
    osize, oend = overlay(args.sdcc)
    print(f'PLAYNET.OVL {osize} bytes, data up to {oend - 1:04X}h')
    size, count, usize = transport(args.assembler)
    assemble(args.assembler, '-DMSXPI_RAM_STASH', f'--inc={INCLUDE}', f'--inc={BUILD}',
             f'--raw={BUILD / "PLAYNET.COM"}', f'--sym={BUILD / "playnet.sym"}', 'playnet.asm')
    com = (BUILD / 'PLAYNET.COM').read_bytes()
    print(f'transports: MSXPi {size} bytes, {count} relocations; UNAPI {usize} bytes; PLAYNET.COM {len(com)} bytes')


if __name__ == '__main__':
    main()
