#!/usr/bin/env python3
"""Build PLAYNET.COM (MSXPi path) and its relocatable MSXPi transport.

    python build.py [--assembler sjasmplus]        -> build/PLAYNET.COM, build/transport_msxpi.inc

The transport is assembled at two origins (0 and 100h); every byte that differs is the high byte of an
address inside it, so the word before it is relocated by the loader when it copies the transport to a
game's netplay.transport_area. The game stubs themselves are built by their ROM-Patcher packages
(software/ROM-Patcher/profiles/<game>/rebuild.py), from engine/playnet_engine.asm.
"""
import argparse
from pathlib import Path
import re
import subprocess

HERE = Path(__file__).resolve().parent
BUILD = HERE / 'build'
INCLUDE = HERE.parents[2] / 'asm-common/include'


def assemble(assembler, *args):
    done = subprocess.run([assembler, *args], cwd=HERE, capture_output=True, text=True)
    if done.returncode:
        raise SystemExit(done.stdout + done.stderr)


def symbols(path):
    found = {}
    for line in Path(path).read_text().splitlines():
        match = re.match(r'([\w.]+):\s*EQU\s*0x([0-9A-Fa-f]+)', line)
        if match:
            found[match[1]] = int(match[2], 16)
    return found


def transport(assembler):
    images = []
    for origin in (0, 0x100):
        raw = BUILD / f'transport_{origin:x}.bin'
        sym = BUILD / f'transport_{origin:x}.sym'
        assemble(assembler, f'-DTORG={origin}', f'--raw={raw}', f'--sym={sym}', 'transport_msxpi.asm')
        images.append(raw.read_bytes())
    low, high = images
    assert len(low) == len(high)
    relocs = []
    for i, (a, b) in enumerate(zip(low, high)):
        if a != b:
            assert b - a == 1 and i > 0, 'unexpected difference at %d' % i
            relocs.append(i - 1)
    names = symbols(BUILD / 'transport_0.sym')
    (BUILD / 'transport_msxpi.bin').write_bytes(low)
    lines = ['; generated by build.py from transport_msxpi.asm - do not edit',
             f'TR_SIZE:        EQU     {len(low)}',
             f'TR_IRQ:         EQU     {names["tIrq"] + 1}      ; XIRQ jump target (the game\'s interrupt handler)',
             f'TR_LEN:         EQU     {names["tLen"]}     ; game packet length L',
             f'TR_IMAGE:       EQU     {names["tImage"]}     ; the image\'s AB header',
             f'TR_RET:         EQU     {names["tRet"]}     ; PLAYNET.COM\'s return routine, 0 = reset',
             f'TR_DOSA8:       EQU     {names["tDosA8"]}     ; MSX-DOS\'s slot registers',
             f'TR_DOSSUB:      EQU     {names["tDosSub"]}',
             f'TR_BOOT:        EQU     {names["xBoot"]}    ; the fallback reset, from the return routine',
             'trImage:        INCBIN  "transport_msxpi.bin"',
             'trRelocs:       defw    ' + ', '.join(str(r) for r in relocs) + ', $FFFF']
    (BUILD / 'transport_msxpi.inc').write_text('\n'.join(lines) + '\n')
    return len(low), len(relocs)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--assembler', default='sjasmplus')
    args = parser.parse_args()
    BUILD.mkdir(exist_ok=True)
    size, count = transport(args.assembler)
    assemble(args.assembler, '-DMSXPI_RAM_STASH', f'--inc={INCLUDE}', f'--inc={BUILD}',
             f'--raw={BUILD / "PLAYNET.COM"}', f'--sym={BUILD / "playnet.sym"}', 'playnet.asm')
    com = (BUILD / 'PLAYNET.COM').read_bytes()
    print(f'transport {size} bytes, {count} relocations; PLAYNET.COM {len(com)} bytes')


if __name__ == '__main__':
    main()
