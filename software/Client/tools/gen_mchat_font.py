"""Generate src/mchat_font4x8.h from the glyph table below.

Each glyph is 8 hex digits, one per pixel row (top first); the 4 bits of a
digit are the 4 pixel columns, leftmost = bit 3. Caps use rows 1-6, lower
case x-height is rows 2-6, descenders use row 7.

  python gen_mchat_font.py            write the header
  python gen_mchat_font.py "text"     also print the text as ASCII art
"""
