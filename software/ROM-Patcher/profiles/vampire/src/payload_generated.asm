; Fast ready path changes AF only. Bounded slow path preserves registers.
; 18 * 65535 polls gives about 15-17 seconds at 3.58 MHz, including
; MSX I/O/opcode waits. Allow cold player startup before native fallback.
; This is a per-transfer CPU-time limit (shorter on accelerated CPUs).
; Goonies profile only (not generated): a disconnected Pi must not freeze the game.
; CF on a timeout, A = RC_CONNERR (LINK2 hands A to its caller).
GOONIES_WAIT_PASSES equ 18
PAYLOAD_WAIT:
    in a,(0x56)
    or a
    ret z
    push bc
    push de
    ld d,GOONIES_WAIT_PASSES
goonies_wait_pass:
    ld bc,0xffff
goonies_wait_loop:
    in a,(0x56)
    or a
    jr z,goonies_wait_done
    dec bc
    ld a,b
    or c
    jr nz,goonies_wait_loop
    dec d
    jr nz,goonies_wait_pass
    ld a,0xe8
    scf
goonies_wait_done:
    pop de
    pop bc
    ret
; Tail of PAYLOAD_ESCAPE, placed before it so the DOS ROM keeps it in the wait
; hole: the ESC hole is too small for the two-row check. C bit 2 = 0 when
; CTRL+ESC is down, B = port AA to restore, incoming IFF state on the stack.
PAYLOAD_ESCAPE_DONE:
    ld a,b
    out (0xaa),a
    pop af
    jp po,PAYLOAD_ESCAPE_IFF_OFF
    ei
PAYLOAD_ESCAPE_IFF_OFF:
    ld a,c
    pop bc
    and 4
    ret nz
    ld a,0xe2
    scf
    ret
; Abort key is CTRL+ESC: ESC alone stays an ordinary key for programs.
; ESC = row 7 bit 2, CTRL = row 6 bit 1, both active low.
; Preserve row selection, upper PPI bits and the incoming interrupt state.
; No BIOS call: safe with interrupts disabled, no reliance on BSS.
PAYLOAD_ESCAPE:
    push bc
    ld a,i
    push af
    di
    in a,(0xaa)
    ld b,a
    and 0xf0
    or 7
    out (0xaa),a
    in a,(0xa9)
    ld c,a
    ld a,b
    and 0xf0
    or 6
    out (0xaa),a
    in a,(0xa9)
    ; Move CTRL to bit 2: bit 2 stays 0 only if both keys are down.
    rlca
    or c
    ld c,a
    jp PAYLOAD_ESCAPE_DONE
