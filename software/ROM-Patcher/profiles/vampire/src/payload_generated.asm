; Canonical Z80 payload kernel. Generated for zmac and SDCC by generate.py.
; DE=buffer, BC=count, HL=16-bit running sum. Preserves IX/IY and shadows.
; CF error: A=RC_ESCPRESSED, DE/BC/HL describe completed bytes only.
; Polled mode: caller owns link and leaves /WAIT off (UNAPI ETH_END does so).
PAYLOAD_RX:
    ld a,b
    or c
    ret z
PAYLOAD_RX_LOOP:
    ld a,c
    or a
    call z,PAYLOAD_ESCAPE
    ret c
    call PAYLOAD_WAIT
    ret c
    xor a
    out (0x56),a
    call PAYLOAD_WAIT
    ret c
    in a,(0x5a)
 ifdef MSXPI_DRIVER
    call STORE_BYTE
 else
    ld (de),a
 endif
